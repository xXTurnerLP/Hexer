#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_NOTICES.md from the license files of the wraps in subprojects/.

    python tools/make_notices.py

Run it from the repository root after `meson setup` has downloaded the subprojects, and again
whenever a wrap is bumped. Each dependency's directory comes from its .wrap file, so a version bump
only needs a rerun. The packages (Windows zip, Linux tar.gz, AppImage) ship the file next to LICENSE.
"""
import configparser
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SUB = ROOT / "subprojects"


def wrap_dir(wrap):
    cp = configparser.ConfigParser(interpolation=None)
    cp.read(SUB / (wrap + ".wrap"), encoding="utf-8")
    for section in cp.sections():
        if cp.has_option(section, "directory"):
            d = SUB / cp.get(section, "directory")
            if not d.is_dir():
                sys.exit(f"{d} is missing: run meson setup first")
            return d
    sys.exit(f"{wrap}.wrap has no directory")


def read(wrap, rel):
    return (wrap_dir(wrap) / rel).read_text(encoding="utf-8").strip()


def version(wrap):
    name = wrap_dir(wrap).name
    m = re.search(r"-(\d[\w.]*?)(-docking)?$", name)
    return m.group(1) if m else ""


def lua_notice():
    h = read("lua", "src/lua.h")
    start = h.index("* Copyright (C) 1994")
    block = h[start:h.index("*****", start)]
    return "\n".join(re.sub(r"^\* ?", "", line) for line in block.strip().splitlines()).strip()


def freetype_year():
    m = re.search(r"Copyright \(C\) 1996-(\d{4})", read("freetype2", "include/freetype/freetype.h"))
    return m.group(1) if m else "2026"


PARTS = [
    (f"Dear ImGui {version('imgui-docking')} (docking)", "https://github.com/ocornut/imgui", "MIT",
     lambda: read("imgui-docking", "LICENSE.txt")),
    ("ProggyForever (Dear ImGui's built-in fallback font)", "https://github.com/ocornut/proggyforever", "MIT",
     lambda: "Copyright (c) 2026 Disco Hello, Copyright (c) 2019,2023 Tristan Grimmer\n\n"
             "Distributed under the MIT license (same text as Dear ImGui's above)."),
    (f"GLFW {version('glfw')}", "https://www.glfw.org", "zlib", lambda: read("glfw", "LICENSE.md")),
    (f"Lua {version('lua')}", "https://www.lua.org", "MIT", lua_notice),
    (f"FreeType {version('freetype2')}", "https://freetype.org", "FreeType License (FTL)",
     lambda: f"Portions of this software are copyright (c) {freetype_year()} The FreeType Project "
             "(https://freetype.org).\nAll rights reserved.\n\n" + read("freetype2", "docs/FTL.TXT")),
    (f"Native File Dialog Extended {version('nativefiledialog-extended')}",
     "https://github.com/btzy/nativefiledialog-extended", "zlib",
     lambda: "By Bernard Teo and contributors, based on Michael Labbe's Native File Dialog.\n\n"
             + read("nativefiledialog-extended", "LICENSE")),
    ("Zydis", "https://github.com/zyantific/zydis", "MIT", lambda: read("zydis", "LICENSE")),
    ("Zycore", "https://github.com/zyantific/zycore-c", "MIT", lambda: read("zycore", "LICENSE")),
]


def main():
    out = ["# Third-party notices", "",
           "Hexer itself is MIT licensed (see LICENSE). Its binaries include the following third-party",
           "software, each under its own license. (doctest is used by the test suite only and is not shipped.)",
           "", "<!-- Generated by tools/make_notices.py; do not edit by hand. -->", ""]
    for name, url, lic, text in PARTS:
        out += ["## " + name, "", url + " - " + lic, "", "```", text(), "```", ""]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
