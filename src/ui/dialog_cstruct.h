#pragma once
// "C struct -> parser" window: paste C struct definitions, pick the parser name / root struct /
// endianness / packing, and see the generated Lua parser (core/cstruct.h) update live. Then
//   * "Save as parser..." writes <scripts_dir>/<name>.lua (asks before overwriting an existing
//     file); the script engine's hot reload picks it up like any user script.
//   * "Apply at cursor" hands the Lua source + parser name to the app, which runs it once at the
//     cursor of the active document (e.g. ScriptEngine::run_source, then
//     ScriptEngine::parse(doc, name, cursor, UINT64_MAX)).
// Self-contained: no App dependency. The app owns one CStructDialog, calls open() from a menu /
// palette action and draw() every frame (draw() does nothing while the window is closed).
#include <functional>
#include <string>

#include "core/cstruct.h"

struct ImFont;

namespace hx {

struct CStructDialogCallbacks {
    // Directory for "Save as parser..." (the user scripts dir). "" = button disabled.
    std::string scripts_dir;
    // Writes the file (after the overwrite question). Optional; default: os_write_whole_atomic
    // (creating scripts_dir if needed). Return false and set *err on failure.
    std::function<bool(const std::string& path, const std::string& lua, std::string* err)> save;
    // Runs `lua` (which registers hx.parser{name = parser_name}) once at the cursor of the active
    // document. Return false and set *err to show an error. Null = button disabled.
    std::function<bool(const std::string& lua, const std::string& parser_name, std::string* err)> apply_at_cursor;
    // Short status-bar notice ("Saved parser to ..."). Optional.
    std::function<void(const std::string& msg)> status;
};

class CStructDialog {
public:
    CStructDialog();  // `source` starts with a small example

    void open();      // show (and focus) the window
    void close() { open_ = false; }
    bool is_open() const { return open_; }

    // Draws the window `title` (Begin/End inside) while open. `mono` = font for the code panes
    // (nullptr = current font), `ui_scale` scales the default size.
    void draw(const char* title, ImFont* mono, float ui_scale, const CStructDialogCallbacks& cb);

    // Input (public for persistence / tests). Call mark_dirty() after changing them directly.
    std::string source;
    CStructOptions options;
    void mark_dirty() { dirty_ = true; }

    // Output of the last conversion (regenerated by draw() when the input changed, or now).
    void regenerate();
    const std::string& lua() const { return lua_; }
    const std::string& error() const { return error_; }  // "" = ok
    const CStructInfo& info() const { return info_; }

    // The file "Save as parser..." writes: <dir>/<parser name with unsafe characters -> '_'>.lua
    static std::string script_path(const std::string& dir, const std::string& parser_name);

private:
    void do_save(const std::string& path, const CStructDialogCallbacks& cb);

    bool open_ = false;
    bool focus_ = false;
    bool dirty_ = true;
    std::string lua_, error_;
    CStructInfo info_;
    std::string message_;        // result of the last save / apply
    bool message_is_error_ = false;
    std::string pending_path_;   // overwrite question open for this file
};

}  // namespace hx
